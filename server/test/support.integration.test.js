// Opt-in, only against the disposable local taskgenie_kyc_test[_N] database.
const { test } = require('node:test');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');

test('guest tickets use scoped expiring access and idempotent creation', {
  skip: process.env.KYC_INTEGRATION_TEST !== '1', timeout: 30000,
}, async t => {
  const port = Number(process.env.KYC_TEST_PORT);
  const dbName = process.env.KYC_TEST_DB_NAME || 'taskgenie_kyc_test';
  assert(Number.isInteger(port) && port > 1024 && port < 65536);
  assert(/^taskgenie_kyc_test(?:_\d+)?$/.test(dbName));
  Object.assign(process.env, { NODE_ENV: 'test', DATABASE_URL: '', DB_HOST: '127.0.0.1', DB_PORT: String(port), DB_USER: 'postgres', DB_PASSWORD: '', DB_NAME: dbName, DB_SSL_MODE: 'disable', DB_SSL_CA_FILE: '', PGSSLMODE: '', JWT_SECRET: 'isolated-support-test-secret', AWS_ACCESS_KEY_ID: '', AWS_SECRET_ACCESS_KEY: '', REDIS_URL: '' });
  const express = require('express');
  const db = require('../config/db');
  const app = express(); app.use(express.json()); app.use('/api/support', require('../routes/supportRoutes'));
  app.use((_error, _req, res, _next) => res.status(500).json({ error: 'Request failed' }));
  const server = await new Promise(resolve => { const listener = app.listen(0, '127.0.0.1', () => resolve(listener)); });
  t.after(async () => { await new Promise(resolve => server.close(resolve)); await db.end(); });
  const origin = `http://127.0.0.1:${server.address().port}`;
  const requestId = crypto.randomUUID();
  const payload = { name: 'Fixture Guest', email: 'guest@example.com', subject: 'Fixture subject', message: 'Synthetic ticket message', category: 'general' };
  const create = body => fetch(`${origin}/api/support/tickets`, { method: 'POST', headers: { 'Content-Type': 'application/json', 'Idempotency-Key': requestId }, body: JSON.stringify(body) });
  const [first, second] = await Promise.all([create(payload), create(payload)]);
  assert.equal(first.status, 201); assert.equal(second.status, 201);
  const one = await first.json(); const two = await second.json();
  assert.equal(one.ticket_number, two.ticket_number);
  const count = await db.query('SELECT COUNT(*)::int AS n FROM support_tickets WHERE client_request_id=$1', [requestId]); assert.equal(count.rows[0].n, 1);
  assert.equal((await create({ ...payload, message: 'A different synthetic request' })).status, 409);
  const ticketUrl = `${origin}/api/support/tickets/${one.ticket_number}`;
  assert.equal((await fetch(ticketUrl)).status, 403);
  assert.equal((await fetch(ticketUrl, { headers: { 'x-ticket-token': 'invalid' } })).status, 403);
  assert.equal((await fetch(ticketUrl, { headers: { 'x-ticket-token': one.ticket_token } })).status, 200);
  const jwt = require('jsonwebtoken');
  const emailOnly = jwt.sign({ id: crypto.randomUUID(), role: 'customer', email: payload.email }, process.env.JWT_SECRET);
  assert.equal((await fetch(ticketUrl, { headers: { Authorization: `Bearer ${emailOnly}` } })).status, 401);
  const otherKey = crypto.randomUUID();
  const other = await fetch(`${origin}/api/support/tickets`, { method: 'POST', headers: { 'Content-Type': 'application/json', 'Idempotency-Key': otherKey }, body: JSON.stringify({ ...payload, subject: 'Second fixture' }) });
  const otherTicket = await other.json();
  assert.equal((await fetch(`${origin}/api/support/tickets/${otherTicket.ticket_number}`, { headers: { 'x-ticket-token': one.ticket_token } })).status, 403);
  await db.query("UPDATE support_tickets SET status='closed' WHERE ticket_number=$1", [one.ticket_number]);
  const replyKey = crypto.randomUUID();
  const reply = message => fetch(`${ticketUrl}/reply`, { method: 'POST', headers: { 'Content-Type': 'application/json', 'x-ticket-token': one.ticket_token, 'Idempotency-Key': replyKey }, body: JSON.stringify({ message }) });
  const [firstReply, duplicateReply] = await Promise.all([reply('Synthetic reply'), reply('Synthetic reply')]);
  assert.equal(firstReply.status, 201); assert.equal(duplicateReply.status, 201);
  assert.equal((await firstReply.json()).reply.id, (await duplicateReply.json()).reply.id);
  assert.equal((await reply('Different synthetic reply')).status, 409);
  const thread = await (await fetch(ticketUrl, { headers: { 'x-ticket-token': one.ticket_token } })).json();
  assert.equal(thread.replies.length, 1);
  assert.equal(thread.ticket.status, 'open');
  const customerId = crypto.randomUUID();
  const suffix = crypto.randomBytes(8).toString('hex').toUpperCase();
  await db.query('INSERT INTO users(id,name,email,role,custom_id,password) VALUES($1,$2,$3,$4,$5,$6)', [customerId, 'Fixture Customer', `fixture-${suffix.toLowerCase()}@example.com`, 'customer', `CUS${suffix}`, 'fixture']);
  const fixtureName = `fixture_notifications_${suffix.toLowerCase()}`;
  await db.query(`CREATE FUNCTION ${fixtureName}() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'synthetic notification failure'; END $$`);
  await db.query(`CREATE TRIGGER ${fixtureName} BEFORE INSERT ON notifications FOR EACH ROW WHEN (NEW.user_id = '${customerId}'::uuid) EXECUTE FUNCTION ${fixtureName}()`);
  const auth = jwt.sign({ id: customerId, role: 'customer', name: 'Fixture Customer', email: `fixture-${suffix.toLowerCase()}@example.com` }, process.env.JWT_SECRET);
  const forgedRole = jwt.sign({ id: customerId, role: 'admin' }, process.env.JWT_SECRET);
  assert.equal((await fetch(ticketUrl, { headers: { Authorization: `Bearer ${forgedRole}` } })).status, 403);
  const revoked = jwt.sign({ id: customerId, role: 'customer', nonce: crypto.randomUUID() }, process.env.JWT_SECRET);
  require('../utils/cache').set(`token_revoked:${crypto.createHash('sha256').update(revoked).digest('hex')}`, true, 60000);
  assert.equal((await fetch(ticketUrl, { headers: { Authorization: `Bearer ${revoked}` } })).status, 401);
  const customerKey = crypto.randomUUID();
  const authenticated = () => fetch(`${origin}/api/support/tickets`, { method: 'POST', headers: { 'Content-Type': 'application/json', 'Idempotency-Key': customerKey, Authorization: `Bearer ${auth}` }, body: JSON.stringify(payload) });
  const customerFirst = await authenticated(); const customerSecond = await authenticated();
  assert.equal(customerFirst.status, 201); assert.equal(customerSecond.status, 201);
  assert.equal((await customerFirst.json()).ticket_number, (await customerSecond.json()).ticket_number);
  assert.equal((await db.query('SELECT COUNT(*)::int AS n FROM support_tickets WHERE client_request_id=$1', [customerKey])).rows[0].n, 1);
  process.env.JWT_SECRET = '';
  assert.equal((await create(payload)).status, 503);
});
